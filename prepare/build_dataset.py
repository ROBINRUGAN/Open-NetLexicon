DATASET_RAW_DIR = PROJECT_ROOT / "dataset"             # <project_root>/dataset/<name>/**.pcap
DATASET_OUT_DIR = NETLEXICON_ROOT / "dataset"          # <netlexicon_root>/dataset/<name>/**/<label>.json

BURST_IAT_THRESHOLD_S = 3.0
ACTIVE_IDLE_IAT_THRESHOLD_S = 1.0
WINDOW_BURSTS = 5
HIGH_PORT_VALUE = 1024

# If a label group has too many pcaps, parallelize per-pcap and merge.
LARGE_GROUP_THRESHOLD = 500


# =========================
# PCAP parsing (dpkt)
# =========================

def _parse_pcap_dpkt(pcap_path: str):
    """
    Parse a pcap/pcapng with dpkt.
    Returns a list of (timestamp, Ethernet-or-IP packet). On failure returns [].
    """
    import dpkt
    packets = []
    try:
        with open(pcap_path, "rb") as f:
            magic = f.read(4)
            f.seek(0)
            if magic in (b"\x0a\x0d\x0d\x0a", b"\x0d\x0a\x0d\x0a"):
                # pcapng
                reader = dpkt.pcapng.Reader(f)
            else:
                reader = dpkt.pcap.Reader(f)
            for ts, raw in reader:
                try:
                    eth = dpkt.ethernet.Ethernet(raw)
                    packets.append((float(ts), eth))
                except Exception:
                    # Some captures may not have an Ethernet header.
                    try:
                        ip = dpkt.ip.IP(raw)
                        packets.append((float(ts), ip))
                    except Exception:
                        pass
    except Exception:
        pass
    return packets


def _get_ip(pkt):
    """Extract IPv4/IPv6 from Ethernet or raw IP, else None."""
    import dpkt
    if isinstance(pkt, dpkt.ethernet.Ethernet):
        if isinstance(pkt.data, dpkt.ip.IP):
            return pkt.data
        if isinstance(pkt.data, dpkt.ip6.IP6):
            return pkt.data
        return None
    if isinstance(pkt, (dpkt.ip.IP, dpkt.ip6.IP6)):
        return pkt
    return None


def _get_tcp_udp(ip):
    """Extract TCP/UDP from an IP packet."""
    import dpkt
    if ip is None:
        return None, None
    if isinstance(ip.data, dpkt.tcp.TCP):
        return ip.data, None
    if isinstance(ip.data, dpkt.udp.UDP):
        return None, ip.data
    return None, None


def _pkt_size_dpkt(ip):
    """Packet length capped at 1500 bytes."""
    import dpkt
    if ip is None:
        return 0
    if isinstance(ip, dpkt.ip.IP):
        return min(ip.len, 1500)
    if isinstance(ip, dpkt.ip6.IP6):
        return min(ip.plen + 40, 1500)
    return 0


def _pkt_proto_dpkt(ip):
    """Protocol number. Returns -1 if not IP."""
    import dpkt
    if ip is None:
        return -1
    if isinstance(ip, dpkt.ip.IP):
        return ip.p
    if isinstance(ip, dpkt.ip6.IP6):
        return ip.nxt
    return -1


def _pkt_ipid_dpkt(ip):
    """IPv4 IP ID (IPv6 returns 0)."""
    import dpkt
    if isinstance(ip, dpkt.ip.IP):
        return ip.id
    return 0


def _pkt_src_key_dpkt(ip, tcp, udp):
    """(src_ip_bytes, sport) used to determine flow direction."""
    if ip is None:
        return None
    sport = tcp.sport if tcp else (udp.sport if udp else -1)
    return (ip.src, sport)


def _tcp_flags_int_dpkt(tcp):
    """TCP flags as int; -1 if not TCP."""
    if tcp is None:
        return -1
    return int(tcp.flags)


def _low_port_and_high_port(sport, dport):
    if sport < 0 or dport < 0:
        return -1, -1
    small = min(sport, dport)
    large = max(sport, dport)
    low_port = small if small <= 1023 else HIGH_PORT_VALUE
    high_port = large if large <= 1023 else HIGH_PORT_VALUE
    return low_port, high_port


# =========================
# Seq/ack unwrapping
# =========================

def _unwrap_32bit(ordered_pairs):
    if not ordered_pairs:
        return {}
    mask32 = (1 << 32) - 1
    half = 1 << 31
    out = {}
    prev_idx, prev_raw = ordered_pairs[0]
    prev_u = prev_raw & mask32
    out[prev_idx] = prev_u
    for idx, raw in ordered_pairs[1:]:
        raw = int(raw) & mask32
        delta = raw - (prev_raw & mask32)
        if delta > half:
            delta -= 1 << 32
        elif delta < -half:
            delta += 1 << 32
        prev_u = prev_u + delta
        prev_raw = raw
        out[idx] = prev_u
    return out


def _build_seq_ack_unwrapped_dpkt(parsed_pkts, first_sender_key):
    """
    parsed_pkts: [(ts, ip, tcp, udp, direction), ...]
    direction: 0=fwd, 1=bwd
    """
    seq_list_fwd, seq_list_bwd = [], []
    ack_list_fwd, ack_list_bwd = [], []
    first_syn_idx_fwd = first_syn_idx_bwd = None

    for i, (ts, ip, tcp, udp, direction) in enumerate(parsed_pkts):
        if tcp is None:
            continue
        raw_seq = int(tcp.seq) & 0xFFFFFFFF
        raw_ack = int(tcp.ack) & 0xFFFFFFFF
        flags = int(tcp.flags)
        has_syn = bool(flags & 0x02)
        has_ack = bool(flags & 0x10)
        if direction == 0:
            seq_list_fwd.append((i, raw_seq))
            if has_syn and first_syn_idx_fwd is None:
                first_syn_idx_fwd = i
            if has_ack:
                ack_list_fwd.append((i, raw_ack))
        else:
            seq_list_bwd.append((i, raw_seq))
            if has_syn and first_syn_idx_bwd is None:
                first_syn_idx_bwd = i
            if has_ack:
                ack_list_bwd.append((i, raw_ack))

    u_seq_fwd = _unwrap_32bit(seq_list_fwd)
    u_seq_bwd = _unwrap_32bit(seq_list_bwd)
    u_ack_fwd = _unwrap_32bit(ack_list_fwd)
    u_ack_bwd = _unwrap_32bit(ack_list_bwd)
    unwrapped_seq = {**u_seq_fwd, **u_seq_bwd}
    unwrapped_ack = {**u_ack_fwd, **u_ack_bwd}
    ISN_A = unwrapped_seq.get(first_syn_idx_fwd) if first_syn_idx_fwd is not None else None
    ISN_B = unwrapped_seq.get(first_syn_idx_bwd) if first_syn_idx_bwd is not None else None
    return unwrapped_seq, unwrapped_ack, ISN_A or 0, ISN_B or 0


# =========================
# Feature extraction (dpkt)
# =========================

def extract_packet_features_dpkt(raw_packets):
    """
    raw_packets: [(ts_float, eth_or_ip_pkt), ...]
    Returns (packet_rows, meta). packet_rows is 11-dim per packet (legacy-compatible).
    """
    import dpkt
    if not raw_packets:
        return [], (None,)

    # Pre-extract ip/tcp/udp layers.
    parsed = []
    for ts, pkt in raw_packets:
        ip = _get_ip(pkt)
        tcp, udp = _get_tcp_udp(ip)
        parsed.append((ts, ip, tcp, udp))

    # Determine the first sender key.
    ts0, ip0, tcp0, udp0 = parsed[0]
    first_sender_key = _pkt_src_key_dpkt(ip0, tcp0, udp0)

    # Compute per-packet direction.
    directions = []
    for ts, ip, tcp, udp in parsed:
        key = _pkt_src_key_dpkt(ip, tcp, udp)
        directions.append(0 if (key is None or key == first_sender_key) else 1)

    # Parsed packets with direction.
    parsed_with_dir = [(ts, ip, tcp, udp, d) for (ts, ip, tcp, udp), d in zip(parsed, directions)]

    # Unwrap seq/ack.
    unwrapped_seq, unwrapped_ack, ISN_A, ISN_B = _build_seq_ack_unwrapped_dpkt(
        parsed_with_dir, first_sender_key
    )

    rows = []
    prev_time = parsed[0][0]
    prev_ipid_fwd = prev_ipid_bwd = None

    for i, (ts, ip, tcp, udp, direction) in enumerate(parsed_with_dir):
        size = _pkt_size_dpkt(ip)
        iat_ms = 0.0 if i == 0 else max(0.0, (ts - prev_time) * 1000.0)
        flags = _tcp_flags_int_dpkt(tcp)
        proto = _pkt_proto_dpkt(ip)

        # IPID delta (per direction).
        if ip is not None:
            cur_ipid = _pkt_ipid_dpkt(ip)
            if direction == 0:
                ipid_delta = (cur_ipid - prev_ipid_fwd) if prev_ipid_fwd is not None else -1
                prev_ipid_fwd = cur_ipid
            else:
                ipid_delta = (cur_ipid - prev_ipid_bwd) if prev_ipid_bwd is not None else -1
                prev_ipid_bwd = cur_ipid
        else:
            ipid_delta = -1

        # rel_seq / rel_ack
        if tcp is not None:
            u_seq = unwrapped_seq.get(i)
            u_ack = unwrapped_ack.get(i) if (flags >= 0 and (flags & 0x10)) else None
            if direction == 0:
                rel_seq = (u_seq - ISN_A) if u_seq is not None else -1
                rel_ack = (u_ack - ISN_B) if u_ack is not None else -1
            else:
                rel_seq = (u_seq - ISN_B) if u_seq is not None else -1
                rel_ack = (u_ack - ISN_A) if u_ack is not None else -1
        else:
            rel_seq = rel_ack = -1

        # Ports
        if tcp is not None:
            sport, dport = tcp.sport, tcp.dport
        elif udp is not None:
            sport, dport = udp.sport, udp.dport
        else:
            sport = dport = -1
        low_port, high_port = _low_port_and_high_port(sport, dport)

        rows.append([
            int(size), int(direction), float(round(iat_ms, 4)), int(flags), int(proto), int(i),
            int(ipid_delta), int(rel_seq), int(rel_ack), int(low_port), int(high_port),
        ])
        prev_time = ts

    return rows, (first_sender_key,)


# =========================
# Burst/window stats
# =========================

def compute_burst_boundaries(iats_ms, directions, threshold_ms=3000.0):
    if not iats_ms:
        return []
    boundaries = [0]
    for i in range(1, len(iats_ms)):
        if iats_ms[i] >= threshold_ms:
            boundaries.append(i)
        elif directions[i] != directions[i - 1]:
            boundaries.append(i)
    return boundaries


def _skewness(x):
    if len(x) < 2:
        return 0.0
    x = np.asarray(x, dtype=float)
    m = np.mean(x)
    s = np.std(x)
    if s <= 0:
        return 0.0
    return float(np.mean((x - m) ** 3) / (s ** 3))


def _safe_mean(x, default=0.0):
    return float(np.mean(x)) if x else default


def _safe_std(x, default=0.0):
    return float(np.std(x)) if len(x) >= 2 else default


def _safe_var(x, default=0.0):
    return float(np.var(x)) if len(x) >= 2 else default


FLOW_MISSING = -1.0


def flow_level_features_from_packet_rows(packet_rows, iats_ms):
    n = len(packet_rows)
    if n == 0:
        return [FLOW_MISSING] * 37

    sizes = [r[0] for r in packet_rows]
    dirs = [r[1] for r in packet_rows]
    iats = iats_ms if len(iats_ms) == n else [0.0] + [packet_rows[i][2] for i in range(1, n)]

    fwd_sizes = [s for s, d in zip(sizes, dirs) if d == 0]
    bwd_sizes = [s for s, d in zip(sizes, dirs) if d == 1]
    fwd_count = len(fwd_sizes)
    bwd_count = len(bwd_sizes)
    total_fwd_bytes = sum(fwd_sizes)
    total_bwd_bytes = sum(bwd_sizes)

    duration_sec = (sum(iats) / 1000.0) if n >= 2 and iats else 0.0
    duration_ms = duration_sec * 1000.0
    bytes_per_sec = (total_fwd_bytes + total_bwd_bytes) / duration_sec if duration_sec > 0 else FLOW_MISSING
    fwd_pps = fwd_count / duration_sec if duration_sec > 0 else FLOW_MISSING
    bwd_pps = bwd_count / duration_sec if duration_sec > 0 else FLOW_MISSING

    feat = [
        duration_ms, fwd_count, bwd_count, total_fwd_bytes, total_bwd_bytes,
        _safe_mean(fwd_sizes, default=FLOW_MISSING),
        _safe_mean(bwd_sizes, default=FLOW_MISSING),
        _safe_std(fwd_sizes, default=FLOW_MISSING),
        _safe_std(bwd_sizes, default=FLOW_MISSING),
        bytes_per_sec,
    ]
    feat.extend([
        _safe_mean(sizes, default=FLOW_MISSING),
        _safe_std(sizes, default=FLOW_MISSING),
        _safe_var(sizes, default=FLOW_MISSING),
        float(max(sizes)) if sizes else FLOW_MISSING,
        float(min(sizes)) if sizes else FLOW_MISSING,
        float(max(fwd_sizes)) if fwd_sizes else FLOW_MISSING,
        float(max(bwd_sizes)) if bwd_sizes else FLOW_MISSING,
        _skewness(sizes) if len(sizes) >= 2 else FLOW_MISSING,
    ])

    all_iat = [iats[i] for i in range(1, n)] if n > 1 else []
    fwd_iat = [iats[i] for i in range(1, n) if dirs[i] == 0 and dirs[i - 1] == 0] if n > 1 else []
    bwd_iat = [iats[i] for i in range(1, n) if dirs[i] == 1 and dirs[i - 1] == 1] if n > 1 else []
    feat.extend([
        _safe_mean(all_iat, default=FLOW_MISSING),
        _safe_std(all_iat, default=FLOW_MISSING),
        float(max(all_iat)) if all_iat else FLOW_MISSING,
        float(min(all_iat)) if all_iat else FLOW_MISSING,
        _safe_mean(fwd_iat, default=FLOW_MISSING),
        _safe_std(fwd_iat, default=FLOW_MISSING),
        _safe_mean(bwd_iat, default=FLOW_MISSING),
        _safe_std(bwd_iat, default=FLOW_MISSING),
    ])

    fin = syn = rst = psh = ack = urg = 0
    for r in packet_rows:
        f = r[3]
        if f < 0:
            continue
        if f & 0x01: fin += 1
        if f & 0x02: syn += 1
        if f & 0x04: rst += 1
        if f & 0x08: psh += 1
        if f & 0x10: ack += 1
        if f & 0x20: urg += 1
    feat.extend([fin, syn, rst, psh, ack, urg])

    active_periods, idle_periods = [], []
    if n >= 2:
        thresh_ms = ACTIVE_IDLE_IAT_THRESHOLD_S * 1000.0
        in_active = iats[1] < thresh_ms
        seg_sum = 0.0
        for i in range(1, n):
            if iats[i] < thresh_ms:
                seg_sum += iats[i] / 1000.0
                if not in_active:
                    in_active = True
            else:
                if in_active and seg_sum > 0:
                    active_periods.append(seg_sum)
                seg_sum = 0.0
                in_active = False
                idle_periods.append(iats[i] / 1000.0)
        if in_active and seg_sum > 0:
            active_periods.append(seg_sum)

    feat.extend([
        fwd_pps,
        bwd_pps,
        _safe_mean(active_periods, default=FLOW_MISSING),
        _safe_std(active_periods, default=FLOW_MISSING),
        _safe_mean(idle_periods, default=FLOW_MISSING),
    ])

    return [float(round(x, 6)) for x in feat]


# =========================
# Single pcap (dpkt)
# =========================

def process_one_pcap(pcap_path: Path):
    """Process one pcap. Returns (flow_dict, error_str)."""
    raw_packets = _parse_pcap_dpkt(str(pcap_path))
    if raw_packets is None:
        return None, f"Failed to parse: {pcap_path.name}"
    if not raw_packets:
        return {"flow_id": pcap_path.name, "packets": [], "bursts": [0], "window_stats": []}, None

    packet_rows, _ = extract_packet_features_dpkt(raw_packets)
    iats_ms = [r[2] for r in packet_rows]
    directions = [r[1] for r in packet_rows]
    bursts = compute_burst_boundaries(iats_ms, directions, BURST_IAT_THRESHOLD_S * 1000.0)

    window_stats = []
    for start in range(0, len(bursts) - WINDOW_BURSTS + 1):
        end = start + WINDOW_BURSTS
        start_idx = bursts[start]
        end_idx = bursts[end] if end < len(bursts) else len(packet_rows)
        sub_rows = packet_rows[start_idx:end_idx]
        sub_iats = [0.0] + [sub_rows[i][2] for i in range(1, len(sub_rows))]
        window_stats.append(flow_level_features_from_packet_rows(sub_rows, sub_iats))

    return {
        "flow_id": pcap_path.name,
        "packets": packet_rows,
        "bursts": bursts,
        "window_stats": window_stats,
    }, None


# ================================================================
# multiprocessing workers
# ================================================================

def _process_one_pcap_wrapper(pcap_path_str):
    """Per-pcap worker. Returns (flow_dict, error_str)."""
    flow, err = process_one_pcap(Path(pcap_path_str))
    return flow, err


def _process_group(group_info):
    """
    Per-group worker (small label groups with #pcaps <= LARGE_GROUP_THRESHOLD).
    Processes all pcaps under the group and writes one JSON.
    group_info = (name, subdir_rel_str, label, [pcap_path_str, ...])
    """
    name, subdir_rel_str, label, pcap_paths = group_info

    out_base = DATASET_OUT_DIR / name
    out_dir = out_base if subdir_rel_str == "." else out_base / subdir_rel_str
    out_dir.mkdir(parents=True, exist_ok=True)

    flows_buf = []
    errors = []
    for pcap_path_str in pcap_paths:
        flow, err = process_one_pcap(Path(pcap_path_str))
        if err:
            errors.append(f"[{name}] {subdir_rel_str}/{label} {Path(pcap_path_str).name}: {err}")
            continue
        if flow:
            flows_buf.append(flow)

    if flows_buf:
        out_file = out_dir / f"{label}.json"
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump({"label": label, "flows": flows_buf}, f, ensure_ascii=False, indent=2)

    return len(pcap_paths), len(flows_buf), errors


