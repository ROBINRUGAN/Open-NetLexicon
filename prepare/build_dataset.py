# Entry
# =========================

def run():
    import argparse
    from multiprocessing import Pool, cpu_count
    from collections import defaultdict as dd

    parser = argparse.ArgumentParser(description="Raw PCAP -> JSON feature extraction (dpkt).")
    parser.add_argument("--dataset", type=str, nargs="+", default=None,
                        help="Dataset roots to process (default: all). "
                             "Example: --dataset CipherSpectrum cstnet")
    parser.add_argument("--workers", type=int, default=None,
                        help="Number of worker processes (default: half of CPU cores).")
    args = parser.parse_args()

    dataset_roots = args.dataset if args.dataset else ALL_DATASET_ROOTS
    n_workers = args.workers if args.workers else max(1, cpu_count() // 2)

    # Scan all pcaps and group by (dataset, subdir_rel, label).
    groups = dd(list)
    for name in dataset_roots:
        src_dir = DATASET_RAW_DIR / name
        if not src_dir.is_dir():
            print(f"[skip] missing source dir: {src_dir}")
            continue
        for dirpath, _dirnames, filenames in os.walk(src_dir):
            dirpath = Path(dirpath)
            pcap_files = sorted(f for f in filenames if f.lower().endswith(".pcap"))
            if not pcap_files:
                continue
            rel_parent = dirpath.relative_to(src_dir)
            label = rel_parent.name
            subdir_rel = str(rel_parent.parent)
            for fname in pcap_files:
                groups[(name, subdir_rel, label)].append(str(dirpath / fname))

    if not groups:
        print("No pcap files found.")
        return 0

    total_pcaps = sum(len(v) for v in groups.values())
    print(f"Groups: {len(groups)} | PCAPs: {total_pcaps} | workers: {n_workers}")

    # Split into small groups (per-group) and large groups (per-pcap + merge).
    small_groups = []
    large_groups = []
    for (name, subdir_rel, label), pcap_list in sorted(groups.items()):
        if len(pcap_list) > LARGE_GROUP_THRESHOLD:
            large_groups.append((name, subdir_rel, label, pcap_list))
        else:
            small_groups.append((name, subdir_rel, label, pcap_list))

    total_processed = total_flows = 0

    with Pool(n_workers) as pool:
        # Small groups: per-group parallel.
        if small_groups:
            print(f"\n[small] groups={len(small_groups)} (pcaps/group <= {LARGE_GROUP_THRESHOLD})")
            for n_pcap, n_flow, errors in tqdm(
                pool.imap_unordered(_process_group, small_groups),
                total=len(small_groups), desc="small", unit="group"
            ):
                total_processed += n_pcap
                total_flows += n_flow
                for e in errors:
                    tqdm.write(e)

        # Large groups: per-pcap parallel, then merge/write JSON.
        for name, subdir_rel, label, pcap_list in large_groups:
            n_pcap_total = len(pcap_list)
            print(f"\n[large] {name}/{label}: pcaps={n_pcap_total} (per-pcap parallel)")

            out_base = DATASET_OUT_DIR / name
            out_dir = out_base if subdir_rel == "." else out_base / subdir_rel
            out_dir.mkdir(parents=True, exist_ok=True)
            out_file = out_dir / f"{label}.json"

            flows_buf = []
            errors = []

            for flow, err in tqdm(
                pool.imap_unordered(_process_one_pcap_wrapper, pcap_list),
                total=n_pcap_total, desc=f"  {label}", unit="pcap"
            ):
                if err:
                    errors.append(err)
                elif flow:
                    flows_buf.append(flow)

            for e in errors:
                tqdm.write(e)

            if flows_buf:
                print(f"  write flows={len(flows_buf)} -> {out_file}")
                with open(out_file, "w", encoding="utf-8") as f:
                    json.dump({"label": label, "flows": flows_buf}, f,
                              ensure_ascii=False, indent=2)

            total_processed += n_pcap_total
            total_flows += len(flows_buf)

    print(f"\nDone: pcaps={total_processed} -> flows={total_flows}, json_files={len(groups)}")
    return 0


if __name__ == "__main__":
    sys.exit(run())
