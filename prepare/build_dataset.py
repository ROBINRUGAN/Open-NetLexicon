    "CrossPlatform",
    "ISCXVPN2016",
    "ISCXVPNall",  # NonVPN+VPN merged; 7 classes (VPN dir names)
    "ISCXVPN2016app",  # VPN subset regrouped by app_action (generated by build_iscxvpn_app.py)
    "cstnet",
